use crate::random::rdtsc; // переиспользуем чтение счётчика из random.rs
use spin::Mutex;

// значение счётчика на момент загрузки (точка отсчёта)
static BOOT_TSC: Mutex<u64> = Mutex::new(0);

// сколько тактов в секунде (оценка). const, потому что не меняем
const TSC_HZ: u64 = 2_500_000_000; // ~2.5 миллиарда тактов/сек = 2.5 ГГц

// запомнить точку старта. Вызвать один раз при загрузке
pub fn init() {
    *BOOT_TSC.lock() = rdtsc();
}

// сколько тактов прошло с момента загрузки
pub fn ticks_since_boot() -> u64 {
    // вычитание, которое при переполнении не паникует,
    // а "оборачивается". На практике u64-счётчик не переполнится за сотни лет,
    // но это хорошая привычка — защищаться от переполнения
    rdtsc().wrapping_sub(*BOOT_TSC.lock())
}

// сколько секунд работает ОС (оценка)
pub fn uptime_secs() -> u64 {
    // тактов прошло / тактов в секунде = секунд
    // Вся неточность живёт именно здесь (TSC_HZ — приблизительна)
    ticks_since_boot() / TSC_HZ
}

// разложить секунды на (часы, минуты, секунды)
pub fn uptime_hms() -> (u64, u64, u64) {
    let total = uptime_secs();
    (
        total / 3600,        // часов = всего секунд / (секунд в часе)
        (total % 3600) / 60, // минут = остаток после часов, делённый на 60
        total % 60,          // секунд = остаток после минут
    )
}
